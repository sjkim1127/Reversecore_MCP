"""Benchmark Reporting and Serialization Engine.

Provides formatting utilities to serialize BenchmarkScorecardSummary into
GFM Markdown reports, structured JSON, and persist them across target directories.
"""

from __future__ import annotations

from pathlib import Path

from reversecore_mcp.benchmarks.models import BenchmarkScorecardSummary


class BenchmarkReporter:
    """Formatter and exporter for benchmark scorecard summaries."""

    @staticmethod
    def to_json(summary: BenchmarkScorecardSummary, indent: int = 2) -> str:
        """Serialize benchmark scorecard summary into a JSON string.

        Args:
            summary: Aggregated benchmark scorecard summary.
            indent: Indentation level.

        Returns:
            JSON string representation.
        """
        return summary.to_json(indent=indent)

    @staticmethod
    def to_markdown(summary: BenchmarkScorecardSummary) -> str:
        """Generate a GitHub Flavored Markdown (GFM) evaluation report.

        Args:
            summary: Aggregated benchmark scorecard summary.

        Returns:
            Markdown formatted evaluation report string.
        """
        tpr_status = "PASS" if summary.discovery_rate_tpr_pct >= 75.0 else "WARN"
        cwe_status = "PASS" if summary.cwe_exact_match_rate_pct >= 75.0 else "WARN"
        cvss_status = "PASS" if summary.cvss_tolerance_match_rate_pct >= 75.0 else "WARN"
        poc_status = "PASS" if summary.avg_poc_reduction_pct >= 50.0 else "WARN"

        md = f"""# 🎯 Reversecore_MCP CVE Discovery Benchmark Evaluation Report

**Generated:** {summary.execution_timestamp}
**Duration:** {summary.total_duration_seconds:.2f}s
**Total Targets:** {summary.total_targets}
**Overall Discovery Rate (TPR):** {summary.discovery_rate_tpr_pct:.1f}%

## 📊 Executive Scorecard

| Metric | Score / Value | Status |
| :--- | :--- | :--- |
| **True Positive Rate (TPR)** | {summary.discovered_count}/{summary.total_targets} ({summary.discovery_rate_tpr_pct:.1f}%) | `{tpr_status}` |
| **Mean Time-to-Crash (MTTC)** | {summary.mean_time_to_crash_seconds}s | `PASS` |
| **Average PoC Minimization** | {summary.avg_poc_reduction_pct:.1f}% reduction | `{poc_status}` |
| **CWE Exact Match Rate** | {summary.cwe_exact_match_rate_pct:.1f}% (Hierarchical: {summary.cwe_hierarchical_match_rate_pct:.1f}%) | `{cwe_status}` |
| **CVSS v3.1 Mean Absolute Error** | MAE: {summary.cvss_mean_absolute_error:.2f} (Tolerance: {summary.cvss_tolerance_match_rate_pct:.1f}%) | `{cvss_status}` |
| **Severity Concordance** | {summary.severity_concordance_rate_pct:.1f}% | `PASS` |

---

## 🔬 Target Evaluation Breakdown

| Target ID | Vulnerability Class | GT CWE | Pred CWE | Match | GT CVSS | Pred CVSS | Δ | TTC (s) | PoC Red % | Status |
| :--- | :--- | :--- | :--- | :--- | :--- | :--- | :--- | :--- | :--- | :--- |
"""
        for r in summary.target_results:
            match_badge = (
                "EXACT"
                if r.cwe_exact_match
                else ("HIER" if r.cwe_hierarchical_match else "MISMATCH")
            )
            if r.error_message:
                sanitized_err = r.error_message.replace("|", "/").replace("`", "")
                status_badge = (
                    f"{r.status}: {sanitized_err}"
                    if not sanitized_err.startswith("Error:")
                    else sanitized_err
                )
            elif r.is_true_positive:
                status_badge = "DISCOVERED"
            else:
                status_badge = r.status

            md += (
                f"| `{r.target_id}` | `{r.vulnerability_class}` | `{r.ground_truth_cwe}` | "
                f"`{r.predicted_cwe}` | `{match_badge}` | `{r.ground_truth_cvss:.1f}` | "
                f"`{r.predicted_cvss:.1f}` | `{r.cvss_delta:.2f}` | {r.time_to_crash_seconds:.3f}s | "
                f"{r.poc_reduction_percentage:.1f}% | `{status_badge}` |\n"
            )

        md += """
---

## 🧩 Vulnerability Class Stratification

| Vulnerability Class | Total | Discovered (TP) | Missed (FN) | TPR (%) | Avg TTC (s) | Avg PoC Reduction |
| :--- | :--- | :--- | :--- | :--- | :--- | :--- |
"""
        for vc, stats in sorted(summary.class_breakdown.items()):
            md += (
                f"| **{vc}** | {stats.get('total', 0)} | {stats.get('discovered', 0)} | "
                f"{stats.get('missed', 0)} | {stats.get('tpr_pct', 0.0):.1f}% | "
                f"{stats.get('avg_ttc_s', 0.0):.3f}s | {stats.get('avg_reduction_pct', 0.0):.1f}% |\n"
            )

        md += "\n---\n*Report auto-generated by Reversecore_MCP Benchmark Suite.*\n"
        return md

    @classmethod
    def save_reports(
        cls,
        summary: BenchmarkScorecardSummary,
        output_dir: str | Path,
        output_format: str = "both",
    ) -> dict[str, Path]:
        """Save formatted reports to the target directory.

        Args:
            summary: Aggregated benchmark scorecard summary.
            output_dir: Directory path where reports will be saved.
            output_format: Output format ('markdown', 'json', or 'both').

        Returns:
            Dictionary mapping format ('markdown', 'json') to Path of created file.
        """
        out_path = Path(output_dir)
        out_path.mkdir(parents=True, exist_ok=True)
        saved: dict[str, Path] = {}

        fmt = output_format.strip().lower()

        if fmt in ("markdown", "both", "md"):
            md_path = out_path / "benchmark_report.md"
            md_path.write_text(cls.to_markdown(summary), encoding="utf-8")
            saved["markdown"] = md_path

        if fmt in ("json", "both"):
            json_path = out_path / "benchmark_summary.json"
            json_path.write_text(cls.to_json(summary, indent=2), encoding="utf-8")
            saved["json"] = json_path

        return saved
